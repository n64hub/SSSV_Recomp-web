from scipy import ndimage
R=Path(__file__).resolve().parents[1]
O=R/'diagnostics/hd-eyes'
P=R/'Textures/hd-world'
A=P/'art/eyes'
A.mkdir(parents=True,exist_ok=True)
rom=(R/'sssv.us.z64').read_bytes()
rows=json.loads((O/'inventory.json').read_text())
sheet=Image.open(O/'eyes-final-atlas.png').convert('RGBA')
neutral=Image.open(O/'eyes-neutral-reference.png').convert('RGBA')
ybounds=[(5,122),(123,232),(233,345),(346,447),(448,548),(549,665),(666,756),(757,840),(841,923),(924,1006),(1007,1099),(1100,1205)]
bankrows={('eyes',0x3a570):0,('eyes',0x3a590):1,('eyes',0x3a5d0):2,('eyes2',0x3ac70):3,('eyes2',0x3a5d0):4,('eyes3',0x3b310):5,('eyes4',0x3b9b0):6,('eyes5',0x3a570):7,('eyes5',0x3a590):8,('eyes5',0x3be50):9,('eyes6',0x3c4f0):10,('eyes6',0x3c510):11}
def native_hash(raw,palette):
 data=bytearray()
 for y in range(16):
  line=raw[y*8:y*8+8]
  data.extend(line[4:]+line[:4] if y&1 else line)
 used=sorted({v for b in raw for v in (b>>4,b&15)})
 for i in used:data.extend(palette[i*2:i*2+2]*4)
 data.extend(struct.pack('<HHIHBB',16,16,2<<14,1,0,2))
 return xxhash.xxh3_64_hexdigest(data)
manifest=json.loads((P/'rt64.json').read_text())
manifest['textures']=[x for x in manifest['textures'] if not x['path'].startswith('art/eyes/')]
seen={};coverage=[];transforms=[]
for row in rows:
 name=row['name'];f=row['frame'];r=bankrows[(row['bank'],row['palette'])]
 raw=rom[row['offset']:row['offset']+128];pal=rom[row['palette']:row['palette']+32];digest=native_hash(raw,pal)
 if digest in seen:coverage.append(dict(row,hash=digest,path=seen[digest],alias=True));continue
 x0=max(0,20+f*100);x1=min(sheet.width,120+f*100);y0,y1=ybounds[r]
 im=sheet.crop((x0,y0,x1,y1))
 if r<=6 and f in (2,6,9,10):
  # Native open/brow frames contain no palette-specific eyelid colour.
  # Their identical native hashes must select neutral art for every animal.
  nr=0
  im=neutral.crop((15+f*106,0,121+f*106,120))
 # Discard atlas-neighbour fragments and nearly transparent generation residue.
 pixels=np.array(im); alpha=pixels[:,:,3]; labels,count=ndimage.label(ndimage.binary_opening(alpha>=128,iterations=2))
 if count:
  sizes=np.bincount(labels.ravel());sizes[0]=0; main=labels==sizes.argmax()
  support=ndimage.binary_dilation(main,iterations=2)
  pixels[:,:,3]=np.where(support & (alpha>=8),alpha,0)
  im=Image.fromarray(pixels)
 # Empty edge texels prevent the native wrap mode repeating coloured rims.
 # Padding is part of the texture import, not an added visible border.
 canvas=Image.new('RGBA',(im.width+16,im.height+16),(0,0,0,0));canvas.paste(im,(8,8));im=canvas
 im.save(A/(name+'.png'))
 # Match occupied artwork bounds to the original texture, preserving eye size.
 old=Image.open(O/(name+'.png')).convert('RGBA').getchannel('A').getbbox()
 new=im.getchannel('A').point(lambda a:255 if a>=128 else 0).getbbox()
 if not old or not new:raise ValueError('Empty eye '+name)
 w,h=im.size;sx=(new[2]-new[0])/w/((old[2]-old[0])/16);sy=(new[3]-new[1])/h/((old[3]-old[1])/16)
 tx=new[0]/w-sx*old[0]/16;ty=new[1]/h-sy*old[1]/16
 transforms.append((digest,w,h,sx,sy,tx,ty))
 rel='art/eyes/'+name+'.png';seen[digest]=rel
 manifest['textures'].append(dict(path=rel,hashes={'rt64':digest},operation='preload',shift='none'))
 coverage.append(dict(row,hash=digest,path=rel,alias=False))
# The brain character uses a separate full-square RGBA16 eye.
brain=A/'brain-eye.png'
if brain.exists():
 raw=rom[0x1094f0:0x1094f0+2048];data=bytearray()
 for y in range(32):
  line=raw[y*64:(y+1)*64]
  for x in range(0,64,8):
   word=line[x:x+8];data.extend(word[4:]+word[:4] if y&1 else word)
 digest=xxhash.xxh3_64_hexdigest(data+struct.pack('<HHIHBB',32,32,0,8,2,0))
 manifest['textures'].append(dict(path='art/eyes/brain-eye.png',hashes={'rt64':digest},operation='preload',shift='none'))
(P/'eyes.json').write_text(json.dumps(coverage,indent=2)+'\n')
(P/'rt64.json').write_text(json.dumps(manifest,indent=2)+'\n')
head=['// Generated by tools/register_hd_eyes.py.','#pragma once','namespace RT64::SSSVHDEyes {','inline bool textureUV(uint64_t hash, float &sx, float &sy, float &tx, float &ty, uint32_t width, uint32_t height) {','switch(hash) {']
for dg,w,h,sx,sy,tx,ty in transforms:head.append(f'case 0x{dg}ULL: if(width != {w} || height != {h}) return false; sx={sx:.9f}f; sy={sy:.9f}f; tx={tx:.9f}f; ty={ty:.9f}f; return true;')
head+=['default:return false;','}','}','}']
(R/'lib/rt64/src/gbi/sssv_hd_eyes.h').write_text('\n'.join(head)+'\n')
(O/'registered-eyes.json').write_text(json.dumps(coverage,indent=2))
print(len(coverage),'eye views;',len(seen),'unique native hashes')
