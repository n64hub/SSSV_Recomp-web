"""Register authored menu replacements and their original sprite coordinates.

Reads local reference images only for hashes/alpha bounds; never edits artwork.
Generated artwork remains untouched. UV transforms retain the game's margins
even when an authoring tool returns extra transparent canvas around an icon.
"""
from pathlib import Path
import json
import struct

from PIL import Image
import xxhash

ROOT = Path(__file__).resolve().parents[1]
REF = ROOT / 'diagnostics/hd-menu/references'
PACK = ROOT / 'Textures/hd-menu'
inventory = json.loads((REF.parent / 'inventory.json').read_text())
entries, transforms, coverage = [], {}, []

for item in inventory:
    name, width, height = item['name'], item['width'], item['height']
    if name.startswith('thumbnails-NO_LEVEL_'):
        continue  # Unused placeholders, not playable level thumbnails.
    if name == 'menu-sssv_header':
        relative = 'shared/header-frame.png'
    elif name.startswith('menu-'):
        relative = f'shared/{name}.png'
    else:
        group, stem = name.split('-', 1)
        relative = f'{group}/{stem}.png'
    replacement = PACK / relative
    if not replacement.exists():
        continue
    # Menu Sprite2D callers omit the last row; powercell uses the complete32.
    render_height = height if name == 'menu-powercell' else height - 1
    raw = (REF / f'{name}.bin').read_bytes()
    # RT64 hashes complete64-bit words on the last row, even for widths such
    # as43 or14. Reverse whole words first, then slice exactly like the loader.
    swapped = b''.join(raw[i:i+4][::-1] for i in range(0, len(raw), 4))
    texture_size = (render_height - 1) * width * 2 + ((width + 3) // 4) * 8
    swapped = swapped[:texture_size]
    digest = xxhash.xxh3_64_hexdigest(swapped + struct.pack('<BBHH', 2, 0, 0, 0))
    entries.append({'path': relative, 'hashes': {'rt64': digest},
                    'operation': 'preload', 'shift': 'none'})
    with Image.open(REF / f'{name}.png') as original:
        alpha = original.getchannel('A').crop((0, 0, width, render_height))
        old = alpha.getbbox()
    with Image.open(replacement) as image:
        alpha = image.getchannel('A') if image.mode == 'RGBA' else None
        new = alpha.point(lambda a: 255 if a >= 32 else 0).getbbox() if alpha else (0, 0, *image.size)
        rw, rh = image.size
    if not old or not new:
        raise ValueError(f'Empty replacement: {name}')
    ox0, oy0, ox1, oy1 = old
    if name == 'menu-sssv_header':
        # The ROM has stray opaque pixels above its visible blue border.
        # Align to the actual frame, keeping the approved caption position.
        oy0 = 6
    nx0, ny0, nx1, ny1 = new
    sx = ((nx1 - nx0) / rw) / ((ox1 - ox0) / width)
    sy = ((ny1 - ny0) / rh) / ((oy1 - oy0) / render_height)
    tx = nx0 / rw - ox0 / width * sx
    ty = ny0 / rh - oy0 / render_height * sy
    # Opaque thumbnails use their complete frame, without icon normalization.
    if name.startswith('thumbnails-'):
        sx, sy, tx, ty = 1, 1, 0, 0
    transforms[digest] = (sx, sy, tx, ty, rw, rh)
    coverage.append({'source': name, 'path': relative, 'hash': digest,
                     'native_size': [width, render_height], 'hd_size': [rw, rh]})

config = {'configurationVersion': 3, 'hashVersion': 5,
          'defaultOperation': 'preload', 'defaultShift': 'none'}
header_glyphs = REF.parent / 'header-glyphs.json'
if header_glyphs.exists():
    entries.extend(json.loads(header_glyphs.read_text()))
extras = PACK / 'additional-textures.json'
if extras.exists():
    entries.extend(json.loads(extras.read_text()))
(PACK / 'rt64.json').write_text(json.dumps({'configuration': config, 'textures': entries}, indent=2) + '\n')
(REF.parent / 'registered.json').write_text(json.dumps(coverage, indent=2) + '\n')
lines = ['// Generated by tools/register_hd_menu.py. Authored PNGs are not modified.',
         '#pragma once', '#include <cstdint>',
         'namespace RT64::GBI_S2D {',
         'inline bool menuTextureUV(uint64_t hash, float &sx, float &sy, float &tx, float &ty, uint32_t replacementWidth = 0, uint32_t replacementHeight = 0) {',
         '    switch (hash) {']
for digest, values in sorted(transforms.items()):
    assignments = ' '.join(f'{key} = {value:.9f}f;' for key, value in zip(('sx','sy','tx','ty'), values))
    rw, rh = values[4:]
    # In-flight calls can outlive a texture-pack switch. Only normalize the
    # authored image, not its native fallback or another pack's same hash.
    guard = f'if ((replacementWidth || replacementHeight) && (replacementWidth != {rw} || replacementHeight != {rh})) return false;'
    lines.append(f'        case 0x{digest}ULL: {guard} {assignments} return true;')
lines += ['        default: return false;', '    }', '}', '}']
(ROOT / 'lib/rt64/src/gbi/sssv_hd_menu_uv.h').write_text('\n'.join(lines) + '\n')
print(f'Registered {len(entries)} menu artwork replacements.')
